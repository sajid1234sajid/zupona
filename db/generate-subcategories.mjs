// Generates db/migrations/0006_subcategories.sql from src/data/categories.ts.
//
//   node db/generate-subcategories.mjs
//   npx wrangler d1 execute zupona-v3-db --local  --file=./db/migrations/0006_subcategories.sql
//   npx wrangler d1 execute zupona-v3-db --remote --file=./db/migrations/0006_subcategories.sql
//
// The original seed only carried the eight top-level departments, so the
// second level of the tree existed in the static catalog but never in the
// database. Once the storefront reads from D1 that difference is visible --
// category pages lose their subcategory filters -- so this brings the child
// rows across and repoints each product at the most specific category it
// belongs to.
//
// `products.category_id` afterwards means "the deepest category this product
// is filed under". Queries that filter by a department therefore have to match
// the parent as well, which is what `categoryScopeClause()` in
// src/lib/storefront.ts does.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Same extraction the seed generator uses: pull an exported array literal out
 * of a .ts file and evaluate it as plain JS, with lucide icon identifiers
 * rewritten to strings. */
function readArray(relPath, exportName) {
  const source = fs.readFileSync(path.join(root, relPath), "utf8");
  const startMarker = new RegExp(`export const ${exportName}[^=]*=\\s*\\[`);
  const match = startMarker.exec(source);
  if (!match) throw new Error(`Could not find export ${exportName} in ${relPath}`);

  const open = match.index + match[0].length - 1;
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "[") depth++;
    else if (source[i] === "]") {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`Unbalanced array literal for ${exportName}`);

  const literal = source.slice(open, end).replace(/icon:\s*([A-Za-z_$][\w$]*)/g, 'icon: "$1"');
  return new Function(`return ${literal};`)();
}

function q(value) {
  if (value === undefined || value === null) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

const categories = readArray("src/data/categories.ts", "categories");
const products = readArray("src/data/products.ts", "products");

// Subcategory ids have to be unique across the whole categories table, since
// `slug` carries a UNIQUE constraint and doubles as the id here.
const topLevelIds = new Set(categories.map((category) => category.id));
const seen = new Set(topLevelIds);
const lines = [];

lines.push("-- Generated by db/generate-subcategories.mjs -- do not edit by hand.");
lines.push("--");
lines.push("-- Adds the second level of the category tree, which the original seed");
lines.push("-- omitted, and repoints products at the subcategory they belong to so the");
lines.push("-- storefront can offer subcategory filters from the database.");
lines.push("");

let subcategoryCount = 0;
for (const category of categories) {
  for (const [index, sub] of (category.subcategories ?? []).entries()) {
    if (seen.has(sub.id)) {
      throw new Error(
        `Subcategory id "${sub.id}" collides with another category id; ids double as slugs.`
      );
    }
    seen.add(sub.id);
    subcategoryCount += 1;

    lines.push(
      "INSERT OR IGNORE INTO categories (id, parent_id, name, slug, subtitle, image_url, sort_order, is_active)",
      `VALUES (${q(sub.id)}, ${q(category.id)}, ${q(sub.name)}, ${q(sub.id)}, NULL, ${q(sub.image)}, ${index}, 1);`
    );
  }
}

lines.push("");
lines.push("-- Repoint products at their subcategory. Products without one keep the");
lines.push("-- department they already had.");

let repointed = 0;
for (const product of products) {
  if (!product.subcategoryId) continue;
  if (!seen.has(product.subcategoryId)) {
    throw new Error(`Product "${product.id}" names unknown subcategory "${product.subcategoryId}"`);
  }
  repointed += 1;
  lines.push(
    `UPDATE products SET category_id = ${q(product.subcategoryId)} WHERE id = ${q(product.id)};`
  );
}

const outPath = path.join(root, "db/migrations/0006_subcategories.sql");
fs.writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");

console.log(`Wrote ${path.relative(root, outPath)}`);
console.log(`  ${subcategoryCount} subcategories, ${repointed} products repointed`);
